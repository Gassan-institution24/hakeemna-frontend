// ── Lookups ────────────────────────────────────────────────────────────────────
const BY_CODE = new Map(CHIEF_COMPLAINTS.map((c) => [c.code, c]));

export const getChiefComplaint = (code) => BY_CODE.get(code) || null;

export const getChiefComplaintLabel = (code, lang = 'en') => {
  const item = BY_CODE.get(code);
  if (!item) return code;
  return lang === 'ar' ? item.labelAr || item.label : item.label || item.labelAr;
};
